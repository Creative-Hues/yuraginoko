export function renderHelp(root, { onBack }) {
  const items = HELP_SECTIONS.map((sec) =>
    el('details', { class: 'help-item' }, [
      el('summary', { text: sec.title }),
      el('ul', {}, sec.lines.map((text) => el('li', { text }))),
    ]),
  );
  root.replaceChildren(
    el('div', { class: 'panel wide' }, [
      el('h1', { text: '遊び方' }),
      el('p', { class: 'quiet', text: '見たいところを押すと開きます。' }),
      el('div', { class: 'help-list' }, items),
      el('div', { class: 'row' }, [el('button', { class: 'btn sub', type: 'button', text: 'とじる', onclick: () => onBack() })]),
    ]),
  );
}
